"""### Evaluate Model Performance with a Confusion Matrix
Now, we will generate predictions on our test set and plot a confusion matrix to identify which skin lesion classes are being predicted correctly or incorrectly.
"""

from sklearn.metrics import confusion_matrix, classification_report
import seaborn as sns
import numpy as np
import matplotlib.pyplot as plt

# 1. Generate predictions for the test set
y_pred_probs = model.predict(X_test)
y_pred = np.argmax(y_pred_probs, axis=1)
y_true = np.argmax(y_test, axis=1)

# 2. Compute the confusion matrix
cm = confusion_matrix(y_true, y_pred)

# Class names mapped sequentially from the label encoder / unique classes
# Based on the metadata unique classes sorting
class_names = ['akiec', 'bcc', 'bkl', 'df', 'mel', 'nv', 'vasc']

# 3. Plot the confusion matrix heatmap

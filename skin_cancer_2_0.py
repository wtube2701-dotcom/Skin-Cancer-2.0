"""### Load Pixel Data and Split Dataset (80/20)
Now, we will load the 28x28 pixel RGB dataset, normalize the pixel values, map the target labels (`dx`), and split the data into training (80%) and testing/validation (20%) sets.
"""

import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import LabelEncoder
import tensorflow as tf
from tensorflow.keras.utils import to_categorical

# 1. Load the 28x28 RGB pixel dataset
# This CSV contains the flattened pixel values (28 * 28 * 3 = 2352 columns) and a label column at the end
pixel_df = pd.read_csv('/content/hmnist_28_28_RGB.csv')

# 2. Extract features (pixels) and target label
# The last column 'label' is the target
X = pixel_df.iloc[:, :-1].values
y = pixel_df.iloc[:, -1].values

# 3. Reshape pixels back to 28x28x3 images and normalize values to [0, 1]
X = X.reshape(-1, 28, 28, 3) / 255.0

# 4. One-hot encode the target label
num_classes = len(np.unique(y))
y = to_categorical(y, num_classes=num_classes)

# 5. Split the dataset into 80% training and 20% testing
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.20, random_state=42, stratify=y
)

print(f"Training set shape: {X_train.shape}")
print(f"Testing set shape: {X_test.shape}")

"""### Define and Compile the CNN Model
We will now construct a Convolutional Neural Network architecture designed for image classification tasks.
"""

from tensorflow.keras import layers, models

# Build the CNN model
model = models.Sequential([
    layers.Conv2D(32, (3, 3), activation='relu', input_shape=(28, 28, 3)),
    layers.BatchNormalization(),
    layers.MaxPooling2D((2, 2)),
    layers.Dropout(0.25),

    layers.Conv2D(64, (3, 3), activation='relu'),
    layers.BatchNormalization(),
    layers.MaxPooling2D((2, 2)),
    layers.Dropout(0.25),

    layers.Conv2D(128, (3, 3), activation='relu'),
    layers.BatchNormalization(),
    layers.MaxPooling2D((2, 2)),
    layers.Dropout(0.25),

    layers.Flatten(),
    layers.Dense(256, activation='relu'),
    layers.BatchNormalization(),
    layers.Dropout(0.5),
    layers.Dense(num_classes, activation='softmax')
])

# Compile the model
model.compile(
    optimizer='adam',
    loss='categorical_crossentropy',
    metrics=['accuracy']
)

model.summary()

"""### Train the CNN Model
We will now train the CNN on the 80% training dataset and validate it using the remaining 20% dataset over 10 epochs.
"""

# Train the compiled model
history = model.fit(
    X_train,
    y_train,
    epochs=10,
    batch_size=32,
    validation_data=(X_test, y_test)
)

